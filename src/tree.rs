//! The tree: the traits that [`topics!`](crate::topics) implements on every
//! `Topic` enum and leaf type, and parameter values.

use crate::nav::Seg;
use std::any::Any;
use std::fmt::{self, Display};
use std::hash::{Hash, Hasher};

/// A topic: a level (its `Topic` enum) or a leaf (its leaf type, `git::PushLeaf`).
/// The `T` of a [`Channel`](crate::Channel).
///
/// [`Msg::view`](crate::Msg::view) shows a message as a [`View`](Self::View):
/// the message itself on a leaf, the level's `TopicRef` on a level.
pub trait Topic: Send + Sync + 'static {
    /// What a subscriber on this topic sees: `&PushMsg` on `git.push`,
    /// `git::TopicRef<'a>` on `git`.
    type View<'a>;

    /// The view of an event, from the segments of its subject below this topic.
    #[doc(hidden)]
    fn view<'a>(below: &'a [Seg], payload: &'a dyn Any) -> Self::View<'a>;
}

/// A level: implemented by every `Topic` enum generated with
/// [`topics!`](crate::topics). The root's `Topic` is what [`Channel::new`](crate::Channel::new) takes.
pub trait Level: Topic {}

/// A leaf: the leaf type generated for `name: Message` (`git::PushLeaf`), which
/// tells its message type.
pub trait Leaf: Topic {
    /// The message published on this leaf.
    type Msg: Send + Sync + 'static;
}

/// A leaf whose channels can publish: every leaf but request leaves, which
/// take requests only.
#[diagnostic::on_unimplemented(
    message = "can't publish on `{Self}`",
    label = "only leaves publish, and request leaves take requests only",
    note = "publish on a leaf `name: Message`, send requests with `request` or `scatter`"
)]
pub trait Publish: Topic {
    /// What `publish` takes: the leaf's message.
    type Msg: Send + Sync + 'static;
}

/// A request leaf, `name: Message => Reply` in [`topics!`](crate::topics): its
/// channel sends requests with the leaf's message and answers them with a
/// [`Reply`](Self::Reply).
#[diagnostic::on_unimplemented(
    message = "`{Self}` isn't a request leaf",
    note = "declare a request leaf in `topics!` with `name: Message => Reply`"
)]
pub trait Request: Leaf {
    type Reply: Send + 'static;
}

/// A type that can be a parameter in [`topics!`](crate::topics): `Display` for
/// the subject, `Eq` and `Hash` to match on the value itself.
///
/// Implemented for every `Clone + Eq + Hash + Display + Send + Sync + 'static`
/// type. Floats aren't `Eq`, so they can't be parameters.
#[diagnostic::on_unimplemented(
    message = "`{Self}` can't be a parameter",
    note = "parameters must implement `Clone + Eq + Hash + Display + Send + Sync + 'static`"
)]
pub trait ParamValue: DynValue + Display {}

impl<V: Clone + Eq + Hash + Display + Send + Sync + 'static> ParamValue for V {}

impl PartialEq for dyn ParamValue {
    fn eq(&self, other: &Self) -> bool {
        self.eq_value(other)
    }
}

impl Eq for dyn ParamValue {}

impl Hash for dyn ParamValue {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.hash_value(state);
    }
}

/// A value compared and hashed through `dyn`: parameter values and queue
/// groups. Values of different types are never equal.
#[doc(hidden)]
pub trait DynValue: Send + Sync + 'static {
    fn as_any(&self) -> &dyn Any;
    fn eq_value(&self, other: &dyn DynValue) -> bool;
    fn hash_value(&self, state: &mut dyn Hasher);
    fn type_name(&self) -> &'static str;
}

impl<V: Eq + Hash + Send + Sync + 'static> DynValue for V {
    fn as_any(&self) -> &dyn Any {
        self
    }
    fn eq_value(&self, other: &dyn DynValue) -> bool {
        other.as_any().downcast_ref::<V>() == Some(self)
    }
    fn hash_value(&self, mut state: &mut dyn Hasher) {
        self.hash(&mut state);
    }
    fn type_name(&self) -> &'static str {
        std::any::type_name::<V>()
    }
}

impl PartialEq for dyn DynValue {
    fn eq(&self, other: &Self) -> bool {
        self.eq_value(other)
    }
}

impl Eq for dyn DynValue {}

impl Hash for dyn DynValue {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.hash_value(state);
    }
}

/// The message of an event, for the code generated by [`topics!`](crate::topics).
#[doc(hidden)]
pub fn __payload<M: 'static>(payload: &dyn Any) -> &M {
    payload
        .downcast_ref()
        .expect("events of a leaf carry its message")
}

/// The parameter value of a segment, for the code generated by
/// [`topics!`](crate::topics). Its bound rejects a parameter type that isn't a
/// `ParamValue` where the tree is declared.
#[doc(hidden)]
pub fn __param<V: ParamValue>(seg: &Seg) -> &V {
    (seg.param())
        .and_then(|value| value.as_any().downcast_ref())
        .expect("events have the parameter values of their topics")
}

/// Displays a subject, e.g. `user.id.42.delete`, without building a `String`.
///
/// `%`, `.`, `*`, `>` and whitespace in parameter values are escaped as `%XX`
/// (`user.id.a%2Eb.delete`), so each value stays one segment.
pub(crate) struct Subject<'a>(pub(crate) &'a [Seg]);

impl Display for Subject<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (i, seg) in self.0.iter().enumerate() {
            if i > 0 {
                f.write_str(".")?;
            }
            f.write_str(seg.name())?;
            if let Some(param) = seg.param() {
                write!(f, ".{}", Escaped(param))?;
            }
        }
        Ok(())
    }
}

/// Displays a parameter value as one segment: `%`, `.`, `*`, `>` and
/// whitespace become `%XX`, the hex of their UTF-8 bytes.
pub(crate) struct Escaped<'a>(pub(crate) &'a dyn ParamValue);

impl Display for Escaped<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        struct Escape<'a, 'b>(&'a mut fmt::Formatter<'b>);

        impl fmt::Write for Escape<'_, '_> {
            fn write_str(&mut self, s: &str) -> fmt::Result {
                let mut rest = s;
                while let Some((at, c)) = rest
                    .char_indices()
                    .find(|&(_, c)| matches!(c, '%' | '.' | '*' | '>') || c.is_whitespace())
                {
                    self.0.write_str(&rest[..at])?;
                    for byte in c.encode_utf8(&mut [0; 4]).bytes() {
                        write!(self.0, "%{byte:02X}")?;
                    }
                    rest = &rest[at + c.len_utf8()..];
                }
                self.0.write_str(rest)
            }
        }

        fmt::Write::write_fmt(&mut Escape(f), format_args!("{}", self.0))
    }
}
