//! `at!` and `topics!`.

/// Sub-channel further down the tree. The path is relative to the channel and
/// reads like the subject:
///
/// ```ignore
/// at!(bus, git.push)                 // git.push
/// at!(bus, user.id(alice).delete)    // user.<alice>.delete
/// at!(bus, user.id().delete)         // user.*.delete
/// at!(any_user, delete)              // from a channel on user.*
/// ```
///
/// A parameter is either fixed, `id(alice)`, or a wildcard, `id()` (`id(_)`
/// works too): its value then shows up in [`Msg::params`](crate::Msg::params) and the channel can
/// no longer publish.
///
/// The channel is borrowed, not consumed. Under the hood each segment calls a
/// navigation method generated by [`topics!`](crate::topics).
#[macro_export]
macro_rules! at {
    (@go ($acc:expr) $seg:ident ( ) $($rest:tt)*) => {
        $crate::at!(@next ($acc.$seg($crate::Wild)) $($rest)*)
    };
    (@go ($acc:expr) $seg:ident ( _ ) $($rest:tt)*) => {
        $crate::at!(@next ($acc.$seg($crate::Wild)) $($rest)*)
    };
    (@go ($acc:expr) $seg:ident ( $v:expr ) $($rest:tt)*) => {
        $crate::at!(@next ($acc.$seg($crate::Is($v))) $($rest)*)
    };
    (@go ($acc:expr) $seg:ident $($rest:tt)*) => {
        $crate::at!(@next ($acc.$seg()) $($rest)*)
    };
    (@next ($acc:expr)) => {
        $crate::IntoChannel::into_channel($acc)
    };
    (@next ($acc:expr) . $($rest:tt)+) => {
        $crate::at!(@go ($acc) $($rest)+)
    };
    // An incomplete path (`git.` or nothing) continues with a placeholder
    // name, so that it expands like a complete one and editors can complete it.
    (@next ($acc:expr) .) => {
        $crate::at!(@go ($acc) expected_a_topic_name)
    };

    ($channel:expr $(,)?) => {
        $crate::at!(@go ($crate::Channel::steps(&$channel)) expected_a_topic_name)
    };
    ($channel:expr, $($path:tt)+) => {
        $crate::at!(@go ($crate::Channel::steps(&$channel)) $($path)+)
    };
}

/// Declare a tree of typed topics.
///
/// ```ignore
/// topics! {
///     #[derive(Debug)]
///     topics {
///         git {                       // level: module `topics::git`
///             /// Commits pushed.     // docs of the variant, method and module
///             push: GitPushMsg,       // leaf
///             new(Uuid): GitNewMsg,   // parameter + leaf
///         },
///         user {
///             new: UserNewMsg,        // same name as in git: fine, other module
///             id(Uuid) {              // parameter + level
///                 delete: UserDeleteMsg,
///             },
///         },
///         random.arrow.more: DeepMsg, // `a.x` is `a { x }`
///         other = other,              // mount the tree of another topics! module
///         jobs [Mailer] {             // queue groups of `jobs`
///             run [Shard(u32)]: JobMsg, // queue groups of `jobs.run`
///         },
///     }
/// }
/// ```
///
/// Every level becomes a module with:
/// - an enum `Topic` holding the messages of that level: `topics::Topic`,
///   `topics::git::Topic`, `topics::user::id::Topic`, … Each name is a
///   variant in camel case: `push` is `Topic::Push`, `pull_request` is
///   `Topic::PullRequest`.
/// - a type `Steps` with one method per child, used by
///   [`at!`](crate::at).
/// - for queue groups `[ … ]` right after a level's name (`jobs [Mailer] {`),
///   an enum `Queue` in its module, `topics::jobs::Queue`, and for a leaf
///   (`run [Shard(u32)]: JobMsg`) an enum named after it,
///   `topics::jobs::RunQueue`. These group enums derive
///   `Clone + PartialEq + Eq + Hash`; inner attributes such as
///   `[#![derive(Debug)] A, B]` are added, and variants can have attributes
///   of their own, such as docs. Their values can only be joined on
///   the topic that declares them (the channel's scope), with
///   [`queue`](crate::SubscriptionBuilder::queue). The root's groups go after
///   its name too: `topics [ … ] { … }`.
///   A leaf's enum is also the third type parameter of its channel:
///   `Channel<JobMsg, (), topics::jobs::RunQueue>`.
///
/// Doc comments on a topic document its `Topic` variant, its `Steps` method
/// and, for a level, its module, so editors show them when hovering a
/// [`at!`](crate::at) segment. On a chain `a.b.c: Msg` they document
/// `c`. Both also state the subject, such as `git.push` or `user.id.*.delete`.
/// Generated names take the span of the topic's name: going to the definition
/// of `Topic::Push` or `PushQueue` lands on `push`.
///
/// Names only need to be unique among siblings. Raw identifiers make keywords
/// usable: `r#type` is the segment `type` and `Topic::Type`. Each module does
/// `use super::*`, so messages and parameter types are found as in the
/// surrounding code; for that reason `topics!` must be used at module level.
///
/// The root is written like any level and becomes a `pub` module, like every
/// level. Doc comments before its name document that module; other attributes
/// before it are applied to every `Topic` enum. A wrong topic is reported on
/// its own and left out, so the rest of the tree still expands. Parameter types
/// must implement `Clone + Eq + Hash + Display` (see [`ParamValue`](crate::ParamValue));
/// messages must be `Send + Sync + 'static`.
#[macro_export]
macro_rules! topics {
    ($($tree:tt)*) => {
        $crate::__topics! { $crate $($tree)* }
    };
}
