//! `channel!`, `topic!` and `events!`.

/// New bus rooted at a module declared with [`events!`](crate::events):
/// `channel!(events)` is `Channel::<events::Topic>::new()`.
///
/// Each call creates a separate bus. To share one, clone the channel or use
/// [`topic!`](crate::topic) on it.
#[macro_export]
macro_rules! channel {
    ($($module:ident)::+) => {
        $crate::Channel::<$($module::)+ Topic>::new()
    };
}

/// Sub-channel further down the tree. The path is relative to the channel and
/// reads like the subject:
///
/// ```ignore
/// topic!(bus, git.push)                    // git.push
/// topic!(bus, user.id(alice).delete)       // user.<alice>.delete
/// topic!(bus, user.id().delete)            // user.*.delete
/// topic!(any_user, delete)                 // from a channel on user.*
/// ```
///
/// A parameter is either fixed, `id(alice)`, or a wildcard, `id()` (`id(_)`
/// works too): its value then shows up in [`Msg::params`](crate::Msg::params) and the channel can
/// no longer publish.
///
/// The channel is borrowed, not consumed. Under the hood each segment calls a
/// navigation method generated by [`events!`](crate::events).
#[macro_export]
macro_rules! topic {
    (@go ($acc:expr) $seg:ident ( ) $(. $($rest:tt)+)?) => {
        $crate::topic!(@go ($acc.$seg($crate::Wild)) $($($rest)+)?)
    };
    (@go ($acc:expr) $seg:ident ( _ ) $(. $($rest:tt)+)?) => {
        $crate::topic!(@go ($acc.$seg($crate::Wild)) $($($rest)+)?)
    };
    (@go ($acc:expr) $seg:ident ( $v:expr ) $(. $($rest:tt)+)?) => {
        $crate::topic!(@go ($acc.$seg($crate::Is($v))) $($($rest)+)?)
    };
    (@go ($acc:expr) $seg:ident $(. $($rest:tt)+)?) => {
        $crate::topic!(@go ($acc.$seg()) $($($rest)+)?)
    };
    (@go ($acc:expr)) => {
        $crate::IntoChannel::into_channel($acc)
    };

    ($channel:expr, $($path:tt)+) => {
        $crate::topic!(@go ($crate::Channel::steps(&$channel)) $($path)+)
    };
}

/// Declare a typed event tree.
///
/// ```ignore
/// events! {
///     #[derive(Debug)]
///     pub mod events {
///         git {                       // subtree: module `events::git`
///             push: GitPushMsg,       // leaf
///             new(Uuid): GitNewMsg,   // parameter + leaf
///         },
///         user {
///             new: UserNewMsg,        // same name as in git: fine, other module
///             id(Uuid) {              // parameter + subtree
///                 delete: UserDeleteMsg,
///             },
///         },
///         random => arrow => more: DeepMsg, // `a => x` is `a { x }`
///         other = other,              // mount the tree of another events! module
///     }
/// }
/// ```
///
/// Every level becomes a module with:
/// - an enum `Topic` holding the events of that level: `events::Topic`,
///   `events::git::Topic`, `events::user::id::Topic`, …
/// - a type `Steps` with one method per child, used by
///   [`topic!`](crate::topic).
///
/// Names only need to be unique among siblings. Each module does
/// `use super::*`, so messages and parameter types are found as in the
/// surrounding code; for that reason `events!` must be used at module level.
///
/// Attributes are applied to every generated enum. Parameter types must
/// implement `Clone + Eq + Hash + Display` (see [`ParamValue`](crate::ParamValue));
/// messages must be `Send + Sync + 'static`.
#[macro_export]
macro_rules! events {
    // ---------- end of a level: `Topic`, `Steps` and the child modules ----------
    (@munch [$(#[$m:meta])*] [$($v:tt)*] [$($e:tt)*] [$($a:tt)*] [$($s:tt)*]) => {
        $(#[$m])*
        pub enum Topic { $($v)* }

        impl $crate::Node for Topic {
            fn step(&self) -> $crate::Step<'_> {
                match self { $($a)* }
            }
        }

        /// Navigation from this level: one method per child.
        pub struct Steps<P>($crate::Channel<Topic, P>);

        // method names are topic names, so naming conventions don't apply
        #[allow(clippy::new_ret_no_self, clippy::wrong_self_convention, clippy::should_implement_trait)]
        impl<P: 'static> Steps<P> {
            $($s)*
        }

        impl $crate::Navigable for Topic {
            type Steps<P: 'static> = Steps<P>;
            fn steps<P: 'static>(channel: $crate::Channel<Topic, P>) -> Steps<P> {
                Steps(channel)
            }
        }

        impl<P: 'static> $crate::IntoChannel for Steps<P> {
            type T = Topic;
            type P = P;
            fn into_channel(self) -> $crate::Channel<Topic, P> {
                self.0
            }
        }

        $($e)*
    };

    // ---------- `a => rest` is sugar for `a { rest }` ----------
    (@munch $attrs:tt $v:tt $e:tt $a:tt $s:tt $var:ident => $($rest:tt)*) => {
        $crate::events!(@chain $attrs $v $e $a $s [$var] [] $($rest)*);
    };
    (@munch $attrs:tt $v:tt $e:tt $a:tt $s:tt $var:ident $p:tt => $($rest:tt)*) => {
        $crate::events!(@chain $attrs $v $e $a $s [$var $p] [] $($rest)*);
    };
    (@chain $attrs:tt $v:tt $e:tt $a:tt $s:tt [$($head:tt)*] [$($acc:tt)*] , $($rest:tt)*) => {
        $crate::events!(@munch $attrs $v $e $a $s $($head)* { $($acc)* }, $($rest)*);
    };
    (@chain $attrs:tt $v:tt $e:tt $a:tt $s:tt [$($head:tt)*] [$($acc:tt)*]) => {
        $crate::events!(@munch $attrs $v $e $a $s $($head)* { $($acc)* });
    };
    (@chain $attrs:tt $v:tt $e:tt $a:tt $s:tt $head:tt [$($acc:tt)*] $t:tt $($rest:tt)*) => {
        $crate::events!(@chain $attrs $v $e $a $s $head [$($acc)* $t] $($rest)*);
    };

    // ---------- prisms for one variant ----------
    (@plain $var:ident) => {
        $crate::Plain::new(
            stringify!($var),
            |a: &Topic| match a {
                Topic::$var(x) => Some(x),
                #[allow(unreachable_patterns)]
                _ => None,
            },
            Topic::$var,
        )
    };
    (@project $var:ident) => {
        |a: &Topic| match a {
            Topic::$var(v, x) => Some((v, x)),
            #[allow(unreachable_patterns)]
            _ => None,
        }
    };

    // ---------- subtree:  git { ... } ----------
    (@munch $attrs:tt [$($v:tt)*] [$($e:tt)*] [$($a:tt)*] [$($s:tt)*]
        $var:ident { $($inner:tt)* } $(, $($rest:tt)*)?) => {
        $crate::events!(@munch $attrs
            [$($v)* $var($var::Topic),]
            [$($e)* $crate::events!(@module $attrs pub $var { $($inner)* });]
            [$($a)*
                Topic::$var(x) => $crate::Step {
                    name: stringify!($var), param: None, next: Some(x),
                },
            ]
            [$($s)*
                pub fn $var(self) -> $var::Steps<P> {
                    <$var::Topic as $crate::Navigable>::steps(self.0.at_prism($crate::events!(@plain $var)))
                }
            ]
            $($($rest)*)?);
    };

    // ---------- param subtree:  id(Uuid) { ... } ----------
    (@munch $attrs:tt [$($v:tt)*] [$($e:tt)*] [$($a:tt)*] [$($s:tt)*]
        $var:ident ($p:ty) { $($inner:tt)* } $(, $($rest:tt)*)?) => {
        $crate::events!(@munch $attrs
            [$($v)* $var($p, $var::Topic),]
            [$($e)* $crate::events!(@module $attrs pub $var { $($inner)* });]
            [$($a)*
                Topic::$var(p, x) => $crate::Step {
                    name: stringify!($var), param: Some(p as &dyn $crate::ParamValue), next: Some(x),
                },
            ]
            [$($s)*
                pub fn $var<S: $crate::Param<$p>>(self, select: S) -> $var::Steps<$crate::Append<P, S::Q>>
                where
                    P: $crate::AppendParams<S::Q>,
                {
                    let prism = $crate::ParamStep::new(stringify!($var), select, $crate::events!(@project $var), Topic::$var);
                    <$var::Topic as $crate::Navigable>::steps(self.0.at_prism(prism))
                }
            ]
            $($($rest)*)?);
    };

    // ---------- mount:  other = other ----------
    (@munch $attrs:tt [$($v:tt)*] $e:tt [$($a:tt)*] [$($s:tt)*]
        $var:ident = $($m:ident)::+ $(, $($rest:tt)*)?) => {
        $crate::events!(@munch $attrs
            [$($v)* $var($($m::)+ Topic),]
            $e
            [$($a)*
                Topic::$var(x) => $crate::Step {
                    name: stringify!($var), param: None, next: Some(x),
                },
            ]
            [$($s)*
                pub fn $var(self) -> <$($m::)+ Topic as $crate::Navigable>::Steps<P> {
                    <$($m::)+ Topic as $crate::Navigable>::steps(self.0.at_prism($crate::events!(@plain $var)))
                }
            ]
            $($($rest)*)?);
    };

    // ---------- leaf:  push: GitPushMsg ----------
    (@munch $attrs:tt [$($v:tt)*] $e:tt [$($a:tt)*] [$($s:tt)*]
        $var:ident : $t:ty $(, $($rest:tt)*)?) => {
        $crate::events!(@munch $attrs
            [$($v)* $var($t),]
            $e
            [$($a)*
                Topic::$var(_) => $crate::Step {
                    name: stringify!($var), param: None, next: None,
                },
            ]
            [$($s)*
                pub fn $var(self) -> $crate::Channel<$t, P> {
                    self.0.at_prism($crate::events!(@plain $var))
                }
            ]
            $($($rest)*)?);
    };

    // ---------- param leaf:  new(Uuid): GitNewMsg ----------
    (@munch $attrs:tt [$($v:tt)*] $e:tt [$($a:tt)*] [$($s:tt)*]
        $var:ident ($p:ty) : $t:ty $(, $($rest:tt)*)?) => {
        $crate::events!(@munch $attrs
            [$($v)* $var($p, $t),]
            $e
            [$($a)*
                Topic::$var(p, _) => $crate::Step {
                    name: stringify!($var), param: Some(p as &dyn $crate::ParamValue), next: None,
                },
            ]
            [$($s)*
                pub fn $var<S: $crate::Param<$p>>(self, select: S) -> $crate::Channel<$t, $crate::Append<P, S::Q>>
                where
                    P: $crate::AppendParams<S::Q>,
                {
                    self.0.at_prism($crate::ParamStep::new(stringify!($var), select, $crate::events!(@project $var), Topic::$var))
                }
            ]
            $($($rest)*)?);
    };

    // ---------- one level = one module ----------
    (@module $attrs:tt $vis:vis $name:ident { $($body:tt)* }) => {
        // names are the subject segments, lowercase like NATS subjects
        #[allow(non_snake_case, non_camel_case_types, clippy::enum_variant_names)]
        $vis mod $name {
            #[allow(unused_imports)]
            use super::*;
            $crate::events!(@munch $attrs [] [] [] [] $($body)*);
        }
    };

    // ---------- entry ----------
    ($(#[$m:meta])* $vis:vis mod $name:ident { $($body:tt)* }) => {
        $crate::events!(@module [$(#[$m])*] $vis $name { $($body)* });
    };
}
