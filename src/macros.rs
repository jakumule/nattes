//! `channel!`, `topic!` and `events!`.

/// New bus rooted at a module declared with [`events!`](crate::events):
/// `channel!(events)` is `Channel::<events::Topic>::new()`.
///
/// Each call creates a separate bus. To share one, clone the channel or use
/// [`topic!`](crate::topic) on it.
#[macro_export]
macro_rules! channel {
    ($($module:ident)::+) => {
        $crate::Channel::<$($module::)+ Topic>::new()
    };
}

/// Sub-channel further down the tree. The path is relative to the channel and
/// reads like the subject:
///
/// ```ignore
/// topic!(bus, git.push)                    // git.push
/// topic!(bus, user.id(alice).delete)       // user.<alice>.delete
/// topic!(bus, user.id().delete)            // user.*.delete
/// topic!(any_user, delete)                 // from a channel on user.*
/// ```
///
/// A parameter is either fixed, `id(alice)`, or a wildcard, `id()` (`id(_)`
/// works too): its value then shows up in [`Msg::params`](crate::Msg::params) and the channel can
/// no longer publish.
///
/// The channel is borrowed, not consumed. Under the hood each segment calls a
/// navigation method generated by [`events!`](crate::events).
#[macro_export]
macro_rules! topic {
    (@go ($acc:expr) $seg:ident ( ) $($rest:tt)*) => {
        $crate::topic!(@next ($acc.$seg($crate::Wild)) $($rest)*)
    };
    (@go ($acc:expr) $seg:ident ( _ ) $($rest:tt)*) => {
        $crate::topic!(@next ($acc.$seg($crate::Wild)) $($rest)*)
    };
    (@go ($acc:expr) $seg:ident ( $v:expr ) $($rest:tt)*) => {
        $crate::topic!(@next ($acc.$seg($crate::Is($v))) $($rest)*)
    };
    (@go ($acc:expr) $seg:ident $($rest:tt)*) => {
        $crate::topic!(@next ($acc.$seg()) $($rest)*)
    };
    (@next ($acc:expr)) => {
        $crate::IntoChannel::into_channel($acc)
    };
    (@next ($acc:expr) . $($rest:tt)+) => {
        $crate::topic!(@go ($acc) $($rest)+)
    };
    // An incomplete path (`git.` or nothing) continues with a placeholder
    // name, so that it expands like a complete one and editors can complete it.
    (@next ($acc:expr) .) => {
        $crate::topic!(@go ($acc) expected_a_topic_name)
    };

    ($channel:expr $(,)?) => {
        $crate::topic!(@go ($crate::Channel::steps(&$channel)) expected_a_topic_name)
    };
    ($channel:expr, $($path:tt)+) => {
        $crate::topic!(@go ($crate::Channel::steps(&$channel)) $($path)+)
    };
}

/// Declare a typed event tree.
///
/// ```ignore
/// events! {
///     #[derive(Debug)]
///     events {
///         git {                       // subtree: module `events::git`
///             /// Commits pushed.     // docs of the variant, method and module
///             push: GitPushMsg,       // leaf
///             new(Uuid): GitNewMsg,   // parameter + leaf
///         },
///         user {
///             new: UserNewMsg,        // same name as in git: fine, other module
///             id(Uuid) {              // parameter + subtree
///                 delete: UserDeleteMsg,
///             },
///         },
///         random.arrow.more: DeepMsg, // `a.x` is `a { x }`
///         other = other,              // mount the tree of another events! module
///         jobs [Mailer] {             // queue groups of `jobs`
///             run [Shard(u32)]: JobMsg, // queue groups of `jobs.run`
///         },
///     }
/// }
/// ```
///
/// Every level becomes a module with:
/// - an enum `Topic` holding the events of that level: `events::Topic`,
///   `events::git::Topic`, `events::user::id::Topic`, … Each name is a
///   variant in camel case: `push` is `Topic::Push`, `pull_request` is
///   `Topic::PullRequest`.
/// - a type `Steps` with one method per child, used by
///   [`topic!`](crate::topic).
/// - for queue groups `[ … ]` right after a subtree's name (`jobs [Mailer] {`),
///   an enum `Queue` in its module, `events::jobs::Queue`, and for a leaf
///   (`run [Shard(u32)]: JobMsg`) an enum named after it,
///   `events::jobs::RunQueue`. Both derive
///   `Clone + PartialEq + Eq + Hash`; inner attributes such as
///   `[#![derive(Debug)] A, B]` are added, and variants can have attributes
///   of their own, such as docs. Their values can only be joined on
///   the topic that declares them, with
///   [`queue`](crate::SubscriptionBuilder::queue). The root's groups go after
///   its name too: `events [ … ] { … }`.
///   A leaf's enum is also the third type parameter of its channel:
///   `Channel<JobMsg, (), events::jobs::RunQueue>`.
///
/// Doc comments on an entry document its `Topic` variant, its `Steps` method
/// and, for a subtree, its module, so editors show them when hovering a
/// [`topic!`](crate::topic) segment. On a chain `a.b.c: Msg` they document
/// `c`. Both also state the subject, such as `git.push` or `user.id.*.delete`.
/// Generated names take the span of the entry's name: going to the definition
/// of `Topic::Push` or `PushQueue` lands on `push`.
///
/// Names only need to be unique among siblings. Raw identifiers make keywords
/// usable: `r#type` is the segment `type` and `Topic::Type`. Each module does
/// `use super::*`, so messages and parameter types are found as in the
/// surrounding code; for that reason `events!` must be used at module level.
///
/// The root is written like a subtree and becomes a `pub` module, like every
/// level. Doc comments before its name document that module; other attributes
/// before it are applied to every `Topic` enum. A wrong entry is reported on
/// its own and left out, so the rest of the tree still expands. Parameter types must
/// implement `Clone + Eq + Hash + Display` (see [`ParamValue`](crate::ParamValue));
/// messages must be `Send + Sync + 'static`.
#[macro_export]
macro_rules! events {
    ($($tree:tt)*) => {
        $crate::__events! { $crate $($tree)* }
    };
}
