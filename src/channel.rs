//! [`Channel`]: a typed view on part of the tree.

use crate::bus::Bus;
use crate::event::envelope;
use crate::nav::{Append, AppendParams, Node, Param, Pattern, Seg, SegInfo};
use crate::subscription::{Respond, SubscriptionBuilder};
use crate::tree::{Level, Publish, Request, Topic};
use std::fmt;
use std::marker::PhantomData;
use std::ops::Deref;
use std::sync::Arc;

/// The bus as the channels hold it: subscriptions hold the [`Bus`] itself, so
/// the bus closes when the last channel drops this.
pub(crate) struct Handle(pub(crate) Arc<Bus>);

impl Deref for Handle {
    type Target = Bus;

    fn deref(&self) -> &Bus {
        &self.0
    }
}

impl Drop for Handle {
    fn drop(&mut self) {
        self.0.close();
    }
}

/// Typed view on the topic `T` of a tree; behaves like a bus rooted at `T`.
///
/// `T` is a level's `Topic` enum (`topics::git::Topic`) or a leaf type
/// (`topics::git::PushLeaf`). `P` holds the parameters left as wildcards on the
/// way down. Only fully fixed channels (`P = ()`) can publish.
///
/// Go down the tree with the methods of the level's `Steps` trait, brought in
/// by `use topics::prelude::*`: `bus.git().push()`.
///
/// Every channel of a bus, sub-channels included, keeps it open. Once the last
/// one is dropped, nothing can publish anymore: each subscription yields its
/// buffered messages, then ends.
///
/// A function taking `&Channel<T, P>` accepts any channel, root or not, with
/// or without wildcards:
///
/// ```
/// # use nattes::{topics, Channel, Topic, Wild};
/// # pub struct DeleteMsg;
/// # topics! { topics { user { id(u32) { delete: DeleteMsg } } } }
/// use topics::prelude::*;
///
/// async fn watch<T: Topic, P: 'static>(ch: &Channel<T, P>) {
///     let _sub = ch.subscribe().await;
///     // …
/// }
///
/// # fn main() {
/// # futures::executor::block_on(async {
/// let bus = Channel::<topics::Topic>::new();
/// watch(&bus).await;                             // >
/// watch(&bus.user()).await;                      // user.>
/// watch(&bus.user().id(Wild).delete()).await;    // user.id.*.delete
/// # });
/// # }
/// ```
pub struct Channel<T, P = ()> {
    pub(crate) bus: Arc<Handle>,
    // The path is a value (its segments, flat), not a type: `user.id(alice)` and
    // `user.id(bob)` are both `Channel<user::id::Topic>`, and a mounted tree
    // has the same channel types as a standalone one.
    pub(crate) path: Arc<Node>,
    pub(crate) topic: PhantomData<fn() -> (T, P)>,
}

impl<T, P> Clone for Channel<T, P> {
    fn clone(&self) -> Self {
        Self {
            bus: self.bus.clone(),
            path: self.path.clone(),
            topic: PhantomData,
        }
    }
}

impl<T, P> fmt::Debug for Channel<T, P> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_tuple("Channel")
            .field(&format_args!("{}", Pattern(&self.path.keys())))
            .finish()
    }
}

impl<R: Level> Channel<R> {
    /// New bus with `R` as its root.
    pub fn new() -> Self {
        Self {
            bus: Arc::new(Handle(Arc::default())),
            path: Node::root(),
            topic: PhantomData,
        }
    }
}

impl<R: Level> Default for Channel<R> {
    fn default() -> Self {
        Self::new()
    }
}

impl<T: Topic, P: 'static> Channel<T, P> {
    /// One step down to a topic without parameter; used by the code generated
    /// by [`topics!`](crate::topics).
    #[doc(hidden)]
    pub fn __plain<X: Topic>(&self, info: &'static SegInfo) -> Channel<X, P> {
        Channel {
            bus: self.bus.clone(),
            path: self.path.step(Seg::plain(info), false),
            topic: PhantomData,
        }
    }

    /// One step down through a parameter; used by the code generated by
    /// [`topics!`](crate::topics).
    #[doc(hidden)]
    pub fn __param<X: Topic, V: 'static, S: Param<V>>(
        &self,
        info: &'static SegInfo,
        select: S,
    ) -> Channel<X, Append<P, S::Q>>
    where
        P: AppendParams<S::Q>,
    {
        Channel {
            bus: self.bus.clone(),
            path: select.node(&self.path, info),
            topic: PhantomData,
        }
    }

    /// Everything at or below this channel (NATS `subject.>`).
    pub fn subscribe(&self) -> SubscriptionBuilder<T, P> {
        SubscriptionBuilder::new(self.clone())
    }

    /// Answer the requests sent to this request leaf: awaited, it gives a
    /// [`Responder`](crate::Responder), a stream of
    /// [`Incoming`](crate::Incoming) requests.
    ///
    /// Only responders count for [`request`](Self::request) and
    /// [`scatter`](Self::scatter), and each one gets its own reply token.
    /// Subscribers see the requests too, but can't answer them.
    pub fn respond(&self) -> SubscriptionBuilder<T, P, Respond>
    where
        T: Request,
    {
        SubscriptionBuilder::new(self.clone())
    }
}

impl<T: Topic> Channel<T> {
    /// Publish `msg` here. Returns how many subscriptions it was delivered to.
    ///
    /// The message is first delivered to every subscription with room in its
    /// buffer. Only then does `publish` wait for room in the full buffers of
    /// [`Overflow::Wait`](crate::Overflow::Wait) subscribers. If this future is dropped during that
    /// wait, those subscribers miss the message. Delivery is at most once:
    /// see [delivery guarantees](crate#delivery-guarantees).
    ///
    /// Not on a request leaf, which takes [`request`](Self::request)s only.
    pub async fn publish(&self, msg: T::Msg) -> usize
    where
        T: Publish,
    {
        self.bus.deliver(envelope(&self.path, msg)).await
    }
}

impl<T: Publish> Channel<T> {
    /// Publish every message of `msgs`, in order. Returns how many deliveries
    /// were made in total.
    ///
    /// Cheaper than one [`publish`](Self::publish) per message: the
    /// subscriptions are looked up once, and each buffer takes its messages
    /// under one lock. Queue groups still pick a member per message, and the
    /// buffers of [`Overflow::Wait`](crate::Overflow::Wait) subscribers are
    /// waited on once every buffer with room got its messages.
    pub async fn publish_many(&self, msgs: impl IntoIterator<Item = T::Msg>) -> usize {
        let events: Vec<_> = (msgs.into_iter())
            .map(|msg| envelope(&self.path, msg))
            .collect();
        self.bus.deliver_many(&events).await
    }
}
